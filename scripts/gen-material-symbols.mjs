// Writes electron/projects/material-symbols.ts: every icon name the bundled Material Symbols
// font can draw. Run after bumping the `material-symbols` package: npm run icons:names
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const pkgDir = new URL('../node_modules/material-symbols/', import.meta.url);
const { version } = JSON.parse(readFileSync(new URL('package.json', pkgDir), 'utf8'));
const typings = readFileSync(new URL('index.d.ts', pkgDir), 'utf8');

// index.d.ts lists the names as a tuple type: type MaterialSymbols = ["123", "360", …];
const body = typings.slice(typings.indexOf('['), typings.indexOf(']') + 1);
const names = [...new Set(JSON.parse(body))].sort();
if (names.length < 1000 || names.some((n) => !/^[a-z0-9_]+$/.test(n))) {
  throw new Error(`Unexpected icon list in material-symbols@${version}`);
}

const out = fileURLToPath(new URL('../electron/projects/material-symbols.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/gen-material-symbols.mjs from material-symbols@${version}. Do not edit.
// One space-separated string keeps the module small; split once on load.

export const MATERIAL_SYMBOLS_VERSION = '${version}';

export const MATERIAL_SYMBOL_NAMES: readonly string[] =
  '${names.join(' ')}'.split(' ');
`,
);
console.log(`Wrote ${names.length} icon names (material-symbols@${version}) to ${out}`);
